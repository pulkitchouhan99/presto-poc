#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

// Load environment variables
require('dotenv').config();

// Since we can't use ES modules directly, we'll need to use dynamic import
async function fetchStrapiContent() {
  console.log('🔄 Fetching content from Strapi...');
  
  const STRAPI_URL = process.env.STRAPI_URL || 'http://localhost:1337';
  const STRAPI_API_TOKEN = process.env.STRAPI_API_TOKEN || '';

  if (!STRAPI_API_TOKEN) {
    console.warn('⚠️  Warning: STRAPI_API_TOKEN not set. Using mock data instead.');
    return;
  }

  try {
    // Helper function to fetch from Strapi
    const fetchFromStrapi = async (endpoint) => {
      const url = `${STRAPI_URL}/api${endpoint}`;
      const response = await fetch(url, {
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${STRAPI_API_TOKEN}`
        }
      });

      if (!response.ok) {
        throw new Error(`Failed to fetch ${endpoint}: ${response.statusText}`);
      }

      return response.json();
    };

    // Fetch all content - using populate=* for now
    const [headerRes, footerRes, heroRes, carouselRes] = await Promise.all([
      fetchFromStrapi('/header?populate=*'),
      fetchFromStrapi('/footer?populate=*'),
      fetchFromStrapi('/homepage-hero?populate=*'),
      fetchFromStrapi('/carousel-items?populate=*&sort=order')
    ]);

    // Transform Strapi responses to match our types
    // Note: Strapi v4 returns data directly without attributes wrapper for single types
    const content = {
      header: headerRes.data || null,
      footer: footerRes.data || null,
      hero: heroRes.data || null,
      carousel: carouselRes.data?.map(item => ({
        id: item.id.toString(),
        ...item
      })) || []
    };

    // Generate TypeScript file with fetched content
    const outputContent = `// This file is auto-generated by fetch-strapi-content.js
// Do not edit manually - run 'npm run fetch-content' to update

import type { StrapiHeader, StrapiFooter, StrapiHero, StrapiCarouselItem, StrapiAboutPage } from './strapi-types';

export const strapiContent = ${JSON.stringify(content, null, 2)} as {
  header: StrapiHeader | null;
  footer: StrapiFooter | null;
  hero: StrapiHero | null;
  carousel: StrapiCarouselItem[];
};

// Export fetched content
export { strapiContent };
`;

    // Write to file
    const outputPath = path.join(__dirname, '../src/themes/strapi-powered/data/strapi-content.ts');
    fs.writeFileSync(outputPath, outputContent);

    console.log('✅ Successfully fetched and saved Strapi content!');
    console.log(`📁 Content saved to: ${outputPath}`);

  } catch (error) {
    console.error('❌ Error fetching Strapi content:', error.message);
    console.log('💡 Using mock data as fallback');
    
    // Create a file that exports the mock data
    const fallbackContent = `// Using mock data - Strapi fetch failed
export { mockStrapiContent } from './strapi-types';
export const strapiContent = null;
`;
    
    const outputPath = path.join(__dirname, '../src/themes/strapi-powered/data/strapi-content.ts');
    fs.writeFileSync(outputPath, fallbackContent);
  }
}

// Run if called directly
if (require.main === module) {
  fetchStrapiContent();
}

module.exports = { fetchStrapiContent };